export type AKey = keyof typeof dict.bg;

/** Превежда ключ и замества {name} със стойности. */
export function ta(key: AKey, vars: Record<string, string | number> = {}): string {
  let text: string = dict[getLang()][key];
  for (const [name, value] of Object.entries(vars)) {
    text = text.replace(`{${name}}`, String(value));
  }
  return text;
}

/** Превежда елементите с data-a и data-a-placeholder. */
export function applyGalleryTranslations(): void {
  document.querySelectorAll<HTMLElement>("[data-a]").forEach((el) => {
    el.textContent = ta(el.dataset.a as AKey);
  });
  document.querySelectorAll<HTMLInputElement>("[data-a-placeholder]").forEach((el) => {
    el.placeholder = ta(el.dataset.aPlaceholder as AKey);
  });
  document.title = ta("pageTitle");
}